import Foundation
import GrammarExtraction

/// Generates Swift `Syntax` types from extracted grammar rules.
public enum SyntaxGenerator {

    public struct Output: Sendable {
        /// File name -> Swift source.
        public var files: [String: String]
        /// Names the generator had to guess, unmapped references/tokens, and similar.
        public var warnings: [String]
        /// Informational: types made `indirect` and fields boxed to break reference cycles.
        public var notes: [String] = []
        /// File name -> Swift source of `parse(_:)` functions, for the SQLiteParser module.
        public var parserFiles: [String: String] = [:]
    }

    /// The first line of every generated file; used to recognise files the generator owns.
    public static let header = "// Generated by sqlite-grammar from the SQLite documentation's syntax diagrams. Do not edit."

    public static func generate(rules diagramRules: [GrammarRule], configuration inputConfiguration: CodegenConfiguration) -> Output {
        var configuration = inputConfiguration
        var warnings: [String] = []
        // Helper rules from the configuration join the diagram rules and are always generated.
        var rules = diagramRules
        if !configuration.extraRules.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            do {
                let extras = try GrammarFile.rules(from: configuration.extraRules)
                let defined = Set(diagramRules.map(\.name)).union(extras.map(\.name))
                for var extra in extras {
                    // Kinds were derived from the extra text alone; references may point at diagram rules.
                    for symbol in extra.symbolKinds.keys where defined.contains(symbol) { extra.symbolKinds[symbol] = .reference }
                    rules.append(extra)
                    if !configuration.rules.contains(extra.name) { configuration.rules.append(extra.name) }
                }
            } catch {
                warnings.append("extraRules: \(error)")
            }
        }
        // Patches for syntax SQLite accepts beyond the diagrams.
        let defined = Set(rules.map(\.name))
        for patch in configuration.grammarPatches {
            guard let index = rules.firstIndex(where: { $0.name == patch.rule }) else {
                warnings.append("grammarPatches: no rule \(patch.rule)"); continue
            }
            do {
                if let patched = try GrammarPatching.apply(patch, to: rules[index], defined: defined) {
                    rules[index] = patched
                } else {
                    warnings.append("grammarPatches: \(patch.rule): fragment not found exactly once: \(patch.find)")
                }
            } catch {
                warnings.append("grammarPatches: \(patch.rule): \(error)")
            }
        }
        let byName = Dictionary(rules.map { ($0.name, $0) }, uniquingKeysWith: { _, extra in extra })
        let builder = TypeBuilder(configuration: configuration)

        // Lower every requested rule first, so nullability is known before any reference is typed.
        var lowered: [(GrammarRule, Node)] = []
        let candidates = configuration.rules.compactMap { byName[$0] }.map(RuleRecognition.candidate)
        for name in configuration.rules {
            guard var rule = byName[name] else { warnings.append("rule \(name): no such diagram"); continue }
            // Reference other generated rules where this diagram draws their contents inline.
            let (recognized, referenced) = RuleRecognition.recognize(in: rule.expression, of: name, candidates: candidates)
            precondition(recognized == rule.expression || !referenced.isEmpty)
            rule.expression = recognized
            for r in referenced { rule.symbolKinds[r] = .reference }
            let friendly = rule.expression.typeFriendlyForm { symbol in
                rule.symbolKinds[symbol] != .reference && isFixedToken(symbol)
            }
            let node = lower(friendly, kinds: rule.symbolKinds)
            if case .optional = node { builder.nullableRules.insert(name) }
            lowered.append((rule, node))
        }

        var files: [String: String] = [:]
        let access = configuration.isPublic ? "public " : ""
        let namespace = configuration.namespace
        let indirect = """
            /// Stores a value in an indirect enum case, breaking a reference cycle between structs
            /// (which would otherwise have infinite size) while keeping value semantics.
            @propertyWrapper
            \(access)enum Indirect<Value: Sendable>: Sendable {
                indirect case value(Value)

                \(access)init(wrappedValue: Value) { self = .value(wrappedValue) }

                \(access)var wrappedValue: Value {
                    get { switch self { case .value(let v): return v } }
                    set { self = .value(newValue) }
                }
            }
            """
        if namespace.isEmpty {
            files["GeneratedSupport.swift"] = "\(header)\n\n\(indirect)\n"
        } else {
            files["\(namespace).swift"] = """
                \(header)

                /// Types generated from SQLite's syntax diagrams. See Grammar/codegen.json.
                \(access)enum \(namespace) {}

                extension \(namespace) {
                \(indirect.split(separator: "\n", omittingEmptySubsequences: false).map { $0.isEmpty ? "" : "    " + $0 }.joined(separator: "\n"))
                }

                """
        }
        let decls = lowered.map { rule, node in
            builder.declaration(forRule: rule.name, node: node, grammar: "\(rule.name) ::= \(rule.expression.ebnf)")
        }
        let notes = Recursion.resolve(decls)
        for decl in decls {
            var e = Emitter()
            e.access = access
            e.line(header)
            e.line()
            if namespace.isEmpty {
                e.emit(decl)
                files["\(decl.name).swift"] = e.lines.joined(separator: "\n") + "\n"
            } else {
                e.block("extension \(namespace)") { e in e.emit(decl) }
                files["\(namespace)+\(decl.name).swift"] = e.lines.joined(separator: "\n") + "\n"
            }
        }
        var parserFiles: [String: String] = [:]
        var declarations: [String: TypeDecl] = [:]
        func register(_ d: TypeDecl) { declarations[d.path] = d; d.nested.forEach(register) }
        decls.forEach(register)
        for decl in decls {
            var p = ParserEmitter()
            p.declarations = declarations
            p.e.line(header)
            p.e.line()
            p.e.line("import SQLiteSyntax")
            p.e.line()
            p.emit(decl)
            parserFiles["\(decl.name)+Parsing.swift"] = p.e.lines.joined(separator: "\n") + "\n"
        }
        return Output(files: files, warnings: warnings + builder.warnings, notes: notes, parserFiles: parserFiles)
    }
}
